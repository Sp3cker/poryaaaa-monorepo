/* ARM7 signed multiply timing excludes the operand's sign extension. */
static inline int m4a_pcm_cost_mul(uint32_t operand)
{
    const uint32_t magnitude = operand ^ (0u - (operand >> 31));
    return 1 + (magnitude > 0xFFu) + (magnitude > 0xFFFFu) + (magnitude > 0xFFFFFFu);
}

/* UMLAL timing counts all significant operand bytes. */
static inline int m4a_pcm_cost_umul(uint32_t operand)
{
    return 1 + (operand > 0xFFu) + (operand > 0xFFFFu) + (operand > 0xFFFFFFu);
}

